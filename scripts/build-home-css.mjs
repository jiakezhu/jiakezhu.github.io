import fs from 'node:fs';

// Preserve the homepage's exact cascade and relative asset paths in one request.
const sheets = [
  'refinement.css', 'journal.css', 'story.css',
  'book-transition.css', 'home-v3.css', 'journey.css', 'story-entrance.css',
  'music.css', 'hero-desk.css', 'home-classic.css', 'home-loading.css'
];
const assets = new URL('../assets/', import.meta.url);
const output = new URL('home.css', assets);
const content = '/* Generated by scripts/build-home-css.mjs. Edit the source stylesheets. */\n' +
  sheets.map(file => `\n/* ${file} */\n${fs.readFileSync(new URL(file, assets), 'utf8')}`).join('\n');
if (process.argv.includes('--check')) {
  if (!fs.existsSync(output) || fs.readFileSync(output, 'utf8') !== content) {
    console.error('Homepage CSS is out of date. Run: node scripts/build-home-css.mjs');
    process.exitCode = 1;
  }
} else {
  fs.writeFileSync(output, content);
  console.log(`Built home.css: ${sheets.length} stylesheets in one request (${Buffer.byteLength(content)} bytes).`);
}
